/**
 * SQL units 1-3, written for a true beginner.
 *
 * House rules for every step (keep them when you add lessons):
 *  1. Show the data first. The learner sees the table before any query.
 *  2. Then the query, then exactly what it returns.
 *  3. Plain words before jargon. Define a term the first time it appears.
 *  4. Predict before you write: at least one "what does this return?" question.
 *  5. Finish with a query the learner writes and runs themselves.
 *
 * All three units use the same `orders` table (see dataset.ts), and a test
 * (units123.test.ts) runs every reference query against real SQLite so a
 * displayed result or an expected answer can never drift from the truth.
 */
